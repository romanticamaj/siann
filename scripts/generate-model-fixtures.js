function buildFixture() {
const leaves = [
  { type: 'root', entity: document.root },
  ...document.media.map((entity) => ({ type: 'media', entity })),
  ...document.tracks.map((entity) => ({ type: 'track', entity })),
  ...document.clips.map((entity) => ({ type: 'clip', entity })),
].map(({ type, entity }) => ({ type, id: entity.id, entityHash: sha256Jcs(entity) }));

const out = {
  schemaVersion: 'siann.model_fixtures.v1',
  description: 'A session document with its expected entity hashes (sha256 over RFC 8785 JCS of each entity) and document hash (RFC 6962 Merkle tree, see fixtures/hash/document.json). Entity arrays are sorted by id (ASCII byte order); root.trackOrder is the user-visible track order and deliberately differs from id order. Generated by scripts/generate-model-fixtures.js from the Node bridge hash code.',
  document: {
    ...document,
    media: [...document.media].sort((a, b) => (a.id < b.id ? -1 : 1)),
    tracks: [...document.tracks].sort((a, b) => (a.id < b.id ? -1 : 1)),
    clips: [...document.clips].sort((a, b) => (a.id < b.id ? -1 : 1)),
  },
  entityHashes: leaves,
  documentHash: documentHash(leaves),
};

return out;
}

const FIXTURE_FILE = path.join(__dirname, '..', 'fixtures', 'model', 'session-document-v1.json');

module.exports = { FIXTURE_FILE, buildFixture };

if (require.main === module) {
  const out = buildFixture();
  fs.mkdirSync(path.dirname(FIXTURE_FILE), { recursive: true });
  fs.writeFileSync(FIXTURE_FILE, `${JSON.stringify(out, null, 2)}\n`);
  console.log(`wrote ${FIXTURE_FILE}: ${out.entityHashes.length} entities, ${out.documentHash}`);
}
