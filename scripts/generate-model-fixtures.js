function buildFixture() {
const leaves = [
  { type: 'root', entity: document.root },
  ...document.media.map((entity) => ({ type: 'media', entity })),
  ...document.tracks.map((entity) => ({ type: 'track', entity })),
  ...document.clips.map((entity) => ({ type: 'clip', entity })),
  ...document.pluginSlots.map((entity) => ({ type: 'plugin_slot', entity })),
].map(({ type, entity }) => ({ type, id: entity.id, entityHash: sha256Jcs(entity) }));

const out = {
  schemaVersion: 'siann.model_fixtures.v1',
  description: 'A session document with its expected entity hashes (sha256 over RFC 8785 JCS of each entity) and document hash (RFC 6962 Merkle tree, see fixtures/hash/document.json). Entity arrays are sorted by id (ASCII byte order); root.trackOrder is the user-visible track order and deliberately differs from id order. One track has inserts (plugin slot ids); a track without inserts omits the field, so its hash is the M1 hash. Generated by scripts/generate-model-fixtures.js from the Node bridge hash code.',
  document: {
    ...document,
    media: [...document.media].sort((a, b) => (a.id < b.id ? -1 : 1)),
    tracks: [...document.tracks].sort((a, b) => (a.id < b.id ? -1 : 1)),
    clips: [...document.clips].sort((a, b) => (a.id < b.id ? -1 : 1)),
    pluginSlots: [...document.pluginSlots].sort((a, b) => (a.id < b.id ? -1 : 1)),
  },
  entityHashes: leaves,
  documentHash: documentHash(leaves),
};

return out;
}

// Format v2 (m5-ui-engine-loop-click): the v1 document plus the singleton
// locators entity, both audio-domain frames as decimal strings. Every other
// entity keeps its v1 hash: the schemaVersion string is not hashed.
const locators = {
  schema: 'siann.entity.locators.v1',
  id: 'locators',
  left: '96000',
  right: '4800001',
};

function buildFixtureV2() {
  const v1 = buildFixture();
  const leaves = [...v1.entityHashes, { type: 'locators', id: 'locators', entityHash: sha256Jcs(locators) }];
  return {
    schemaVersion: 'siann.model_fixtures.v1',
    description: 'The document of session-document-v1.json in format siann.session_document.v2, with the singleton locators entity (a single object, ref locators:locators), and its expected entity and document hashes. The other entities keep their v1 hashes: the schemaVersion string is not hashed. Generated by scripts/generate-model-fixtures.js from the Node bridge hash code.',
    document: { ...v1.document, schemaVersion: 'siann.session_document.v2', locators },
    entityHashes: leaves,
    documentHash: documentHash(leaves),
  };
}

const FIXTURE_FILE = path.join(__dirname, '..', 'fixtures', 'model', 'session-document-v1.json');
const FIXTURE_FILE_V2 = path.join(__dirname, '..', 'fixtures', 'model', 'session-document-v2.json');

module.exports = { FIXTURE_FILE, buildFixture, FIXTURE_FILE_V2, buildFixtureV2 };

if (require.main === module) {
  for (const [file, build] of [[FIXTURE_FILE, buildFixture], [FIXTURE_FILE_V2, buildFixtureV2]]) {
    const out = build();
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, `${JSON.stringify(out, null, 2)}\n`);
    console.log(`wrote ${file}: ${out.entityHashes.length} entities, ${out.documentHash}`);
  }
}
