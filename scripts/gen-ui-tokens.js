#!/usr/bin/env node
'use strict';

// The TypeScript mirror of the design tokens. app/renderer/tokens.css is the
// one token source (docs/harness/agent-rules.md, "UI fidelity"); canvas code
// cannot read a stylesheet at module load, so app/src/renderer/tokens.ts
// carries the same names and values, generated here and never edited by hand.
//
//   node scripts/gen-ui-tokens.js           rewrite app/src/renderer/tokens.ts
//   node scripts/gen-ui-tokens.js --check   exit 1 when it is out of date
//
// test/ui-tokens.test.js runs the check, so a token changed in the stylesheet
// alone fails `npm test`.

const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.resolve(__dirname, '..');
const CSS = path.join(ROOT, 'app', 'renderer', 'tokens.css');
const OUT = path.join(ROOT, 'app', 'src', 'renderer', 'tokens.ts');

// The custom properties of every plain `:root { ... }` block, in order; the
// last declaration of a name wins, as in the cascade. Locale and media
// variants (`:root:lang(...)`, `@media`) are not part of the mirror.
function readTokens(css) {
  const text = css.replace(/\/\*[\s\S]*?\*\//g, '');
  const tokens = new Map();
  for (const block of text.matchAll(/(^|[}\s])(:root)\s*\{([^}]*)\}/g)) {
    for (const decl of block[3].matchAll(/(--[\w-]+)\s*:\s*([^;]+);/g)) tokens.set(decl[1].slice(2), decl[2].trim().replace(/\s+/g, ' '));
  }
  return tokens;
}

// A value with its var() references replaced by their values.
function resolve(value, tokens, depth = 0) {
  if (depth > 8) throw new Error(`var() cycle in ${value}`);
  return value.replace(/var\(--([\w-]+)\)/g, (_, name) => {
    if (!tokens.has(name)) throw new Error(`tokens.css uses an undefined token --${name}`);
    return resolve(tokens.get(name), tokens, depth + 1);
  });
}

// `calc(53px * 1)` (a size times the UI scale) as the length it is.
function simplify(value) {
  const product = /^calc\(([\d.]+)px \* ([\d.]+)\)$/.exec(value);
  return product ? `${Number(product[1]) * Number(product[2])}px` : value;
}

function render(tokens) {
  const lines = [
    '// GENERATED by scripts/gen-ui-tokens.js from app/renderer/tokens.css: do not edit.',
    '// The design tokens for code that cannot read the stylesheet (canvas drawing,',
    '// geometry). Values are the :root declarations with var() resolved, sizes at UI',
    '// scale 1. The stylesheet is the source: change a token there and run',
    '// the script (docs/harness/agent-rules.md, "UI fidelity").',
    '',
    'export const TOKENS = {',
  ];
  for (const [name, value] of tokens) lines.push(`  ${JSON.stringify(name)}: ${JSON.stringify(simplify(resolve(value, tokens)))},`);
  lines.push('} as const;', '', 'export type TokenName = keyof typeof TOKENS;', '');
  return lines.join('\n');
}

function generate() {
  return render(readTokens(fs.readFileSync(CSS, 'utf8')));
}

function main(argv) {
  const text = generate();
  if (argv.includes('--check')) {
    const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n') : '';
    if (current !== text) {
      console.error('app/src/renderer/tokens.ts is out of date: run node scripts/gen-ui-tokens.js');
      process.exit(1);
    }
    return;
  }
  fs.writeFileSync(OUT, text);
}

if (require.main === module) main(process.argv.slice(2));

module.exports = { readTokens, resolve, simplify, generate, OUT, CSS };
