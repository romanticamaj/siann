#!/usr/bin/env node
// Regenerates fixtures/protocol/meter-frames.json.
//
// Byte-exact meter frames of the realtime channel, written from the layout in
// docs/schemas/protocol-events-v1.md with Buffer/DataView, independent of the
// native encoder. Little-endian:
//   0  "SMTR"            4 bytes
//   4  u8  version (1)
//   5  u64 epoch
//   13 i64 engineTimestampMicros
//   21 i64 playheadSamples
//   29 u8  playing
//   30 u16 entryCount
//   32 entries: u16 entityIndex, u8 channels, f32 peak[channels], f32 rms[channels]
// Peak and RMS values are exactly representable as f32, so the JSON numbers
// and the bytes agree.
const fs = require('node:fs');
const path = require('node:path');

const MAGIC = 'SMTR';
const VERSION = 1;
const HEADER_BYTES = 32;

function entryBytes(channels) {
  return 3 + 8 * channels;
}

function encodeFrame(frame) {
  const size = HEADER_BYTES + frame.entries.reduce((sum, e) => sum + entryBytes(e.channels), 0);
  const buffer = Buffer.alloc(size);
  const view = new DataView(buffer.buffer, buffer.byteOffset, buffer.byteLength);
  buffer.write(MAGIC, 0, 'ascii');
  view.setUint8(4, VERSION);
  view.setBigUint64(5, BigInt(frame.epoch), true);
  view.setBigInt64(13, BigInt(frame.engineTimestampMicros), true);
  view.setBigInt64(21, BigInt(frame.playheadSamples), true);
  view.setUint8(29, frame.playing ? 1 : 0);
  view.setUint16(30, frame.entries.length, true);
  let offset = HEADER_BYTES;
  for (const entry of frame.entries) {
    view.setUint16(offset, entry.entityIndex, true);
    view.setUint8(offset + 2, entry.channels);
    offset += 3;
    for (const value of [...entry.peak, ...entry.rms]) {
      view.setFloat32(offset, value, true);
      offset += 4;
    }
  }
  return buffer;
}

function decodeFrame(buffer) {
  if (buffer.length < HEADER_BYTES) throw new Error('frame shorter than its header');
  const view = new DataView(buffer.buffer, buffer.byteOffset, buffer.byteLength);
  if (buffer.toString('ascii', 0, 4) !== MAGIC) throw new Error('bad magic');
  if (view.getUint8(4) !== VERSION) throw new Error('bad version');
  const frame = {
    epoch: view.getBigUint64(5, true).toString(),
    engineTimestampMicros: view.getBigInt64(13, true).toString(),
    playheadSamples: view.getBigInt64(21, true).toString(),
    playing: view.getUint8(29) === 1,
    entries: [],
  };
  const count = view.getUint16(30, true);
  let offset = HEADER_BYTES;
  for (let i = 0; i < count; i += 1) {
    if (offset + 3 > buffer.length) throw new Error('truncated entry');
    const entityIndex = view.getUint16(offset, true);
    const channels = view.getUint8(offset + 2);
    if (offset + entryBytes(channels) > buffer.length) throw new Error('truncated entry values');
    offset += 3;
    const values = [];
    for (let c = 0; c < 2 * channels; c += 1) {
      values.push(view.getFloat32(offset, true));
      offset += 4;
    }
    frame.entries.push({ entityIndex, channels, peak: values.slice(0, channels), rms: values.slice(channels) });
  }
  if (offset !== buffer.length) throw new Error('trailing bytes');
  return frame;
}

const FRAMES = [
  {
    name: 'stereo track and master while playing',
    frame: {
      epoch: '3',
      engineTimestampMicros: '1234567890',
      playheadSamples: '96000',
      playing: true,
      entries: [
        { entityIndex: 0, channels: 2, peak: [0.5, 0.25], rms: [0.375, 0.125] },
        { entityIndex: 1, channels: 2, peak: [1, 0.75], rms: [0.5, 0.0625] },
      ],
    },
  },
  {
    name: 'stopped before the first meter block, no entries',
    frame: { epoch: '1', engineTimestampMicros: '0', playheadSamples: '-1', playing: false, entries: [] },
  },
  {
    name: '64-bit extremes and a mono entry',
    frame: {
      epoch: '18446744073709551615',
      engineTimestampMicros: '9223372036854775807',
      playheadSamples: '-9223372036854775808',
      playing: false,
      entries: [{ entityIndex: 65535, channels: 1, peak: [0.5], rms: [0.25] }],
    },
  },
];

function buildFixture() {
  return {
    schemaVersion: 'siann.protocol_fixtures.v1',
    description: 'Meter frames of the realtime channel (docs/schemas/protocol-events-v1.md), little-endian, as lowercase hex. 64-bit values are decimal strings. Generated by scripts/generate-protocol-fixtures.js with DataView, independent of the native encoder.',
    headerBytes: HEADER_BYTES,
    meterFrames: FRAMES.map(({ name, frame }) => ({ name, frame, hex: encodeFrame(frame).toString('hex') })),
  };
}

const FIXTURE_FILE = path.join(__dirname, '..', 'fixtures', 'protocol', 'meter-frames.json');

module.exports = { FIXTURE_FILE, HEADER_BYTES, buildFixture, encodeFrame, decodeFrame, entryBytes };

if (require.main === module) {
  const out = buildFixture();
  fs.mkdirSync(path.dirname(FIXTURE_FILE), { recursive: true });
  fs.writeFileSync(FIXTURE_FILE, `${JSON.stringify(out, null, 2)}\n`);
  console.log(`wrote ${FIXTURE_FILE}: ${out.meterFrames.length} frames`);
}
