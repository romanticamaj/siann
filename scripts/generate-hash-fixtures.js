#!/usr/bin/env node
// Regenerates fixtures/hash/document.json.
//
// This is a deliberately separate, minimal implementation of the SIANN document
// hash (architecture spec, "Canonical JSON and hashes"). It does not import
// src/hash/merkle.js, so the fixture is a cross-check for both the Node and the
// C++ implementations. The RFC 6962 tree itself is anchored by the Certificate
// Transparency vectors in fixtures/hash/rfc6962.json.
const crypto = require('node:crypto');
const fs = require('node:fs');
const path = require('node:path');

const sha = (...parts) => {
  const hash = crypto.createHash('sha256');
  for (const part of parts) hash.update(part);
  return hash.digest();
};

function mth(leafHashes) {
  if (leafHashes.length === 0) return sha(Buffer.alloc(0));
  if (leafHashes.length === 1) return leafHashes[0];
  let k = 1;
  while (k * 2 < leafHashes.length) k *= 2;
  return sha(Buffer.from([1]), mth(leafHashes.slice(0, k)), mth(leafHashes.slice(k)));
}

function expectedDocumentHash(entities) {
  const keyed = entities.map((entity) => ({
    key: `${entity.type}:${entity.id}`,
    digest: Buffer.from(entity.entityHash.slice('sha256:'.length), 'hex'),
  }));
  keyed.sort((a, b) => Buffer.compare(Buffer.from(a.key, 'ascii'), Buffer.from(b.key, 'ascii')));
  const leaves = keyed.map(({ key, digest }) => sha(
    Buffer.from([0]),
    Buffer.from(key, 'ascii'),
    Buffer.from([0]),
    digest,
  ));
  return `sha256:${mth(leaves).toString('hex')}`;
}

const h = (text) => `sha256:${sha(Buffer.from(text, 'utf8')).toString('hex')}`;
const entity = (type, id) => ({ type, id, entityHash: h(`${type}/${id}/content`) });

const valid = [
  ['empty_document', []],
  ['root_only', [entity('root', 'root')]],
  ['two_entities', [entity('root', 'root'), entity('track', 'trk_drums')]],
  ['three_entities_unsorted_input', [
    entity('track', 'trk_bass'),
    entity('root', 'root'),
    entity('clip', 'clp-0001'),
  ]],
  ['five_entities_mixed_types', [
    entity('track', 'trk_vox'),
    entity('plugin_slot', 'slot_A1'),
    entity('root', 'root'),
    entity('clip', 'clp_9'),
    entity('track_lane', 'lane-1'),
  ]],
  ['type_prefix_ordering', [
    entity('track', 'zzz'),
    entity('track_lane', 'aaa'),
    entity('tracks', 'mmm'),
  ]],
].map(([name, entities]) => ({ name, entities, documentHash: expectedDocumentHash(entities) }));

const valid64 = 'a'.repeat(64);
const invalid = [
  ['duplicate_entity', [entity('track', 'trk_1'), entity('track', 'trk_1')], 'duplicate_entity'],
  ['id_with_space', [entity('track', 'trk 1')], 'invalid_entity_id'],
  ['id_empty', [entity('track', '')], 'invalid_entity_id'],
  ['id_too_long', [entity('track', `${valid64}b`)], 'invalid_entity_id'],
  ['id_non_ascii', [entity('track', 'träck')], 'invalid_entity_id'],
  ['type_uppercase', [entity('Track', 'trk_1')], 'invalid_entity_type'],
  ['type_starts_with_digit', [entity('1track', 'trk_1')], 'invalid_entity_type'],
  ['hash_uppercase_hex', [{ type: 'track', id: 'trk_1', entityHash: `sha256:${'A'.repeat(64)}` }], 'invalid_entity_hash'],
  ['hash_missing_prefix', [{ type: 'track', id: 'trk_1', entityHash: 'f'.repeat(64) }], 'invalid_entity_hash'],
  ['hash_short', [{ type: 'track', id: 'trk_1', entityHash: `sha256:${'f'.repeat(63)}` }], 'invalid_entity_hash'],
].map(([name, entities, error]) => ({ name, entities, error }));

const out = {
  schemaVersion: 'siann.document_hash_fixtures.v1',
  description: 'SIANN document hash: RFC 6962 Merkle Tree Hash over leaves sorted by the ASCII bytes of "<type>:<id>". Leaf input is 0x00 || "<type>:<id>" || 0x00 || entityHash bytes. Types match ^[a-z][a-z0-9_]{0,31}$, IDs match ^[A-Za-z0-9_-]{1,64}$, hashes are "sha256:" plus 64 lowercase hex digits. Generated by scripts/generate-hash-fixtures.js.',
  valid,
  invalid,
};

const outFile = path.join(__dirname, '..', 'fixtures', 'hash', 'document.json');
fs.writeFileSync(outFile, `${JSON.stringify(out, null, 2)}\n`);
console.log(`wrote ${outFile}: valid=${valid.length} invalid=${invalid.length}`);
