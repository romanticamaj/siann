#!/usr/bin/env node
// Regenerates fixtures/time/conversions.json.
//
// Reference implementation of the SIANN time conversions (architecture spec,
// "Time model") using arbitrary-precision BigInt, independent of the native
// 128-bit implementation. Rules:
// - 1920 ticks per quarter; superclock rate 282,240,000 per second.
// - Tempo in integer milli-BPM; superclocks per quarter =
//   round(282,240,000 * 60 * 1000 / milliBpm), ties to even.
// - Step tempo changes only; positions before tick 0 use the first tempo.
// - Every conversion rounds to nearest, ties to even (symmetric for negatives).
const fs = require('node:fs');
const path = require('node:path');

const TICKS_PER_QUARTER = 1920n;
const SUPERCLOCK_RATE = 282240000n;
const SCALED_PER_SECOND = SUPERCLOCK_RATE * TICKS_PER_QUARTER;

function roundHalfEven(numerator, denominator) {
  const negative = numerator < 0n;
  const n = negative ? -numerator : numerator;
  let q = n / denominator;
  const r = n % denominator;
  const twice = 2n * r;
  if (twice > denominator || (twice === denominator && q % 2n === 1n)) {
    q += 1n;
  }
  return negative ? -q : q;
}

function superclocksPerQuarter(milliBpm) {
  return roundHalfEven(SUPERCLOCK_RATE * 60n * 1000n, BigInt(milliBpm));
}

function segmentsOf(points) {
  const segments = [];
  let scaled = 0n;
  points.forEach(([tick, milliBpm], index) => {
    if (index > 0) {
      const previous = segments[index - 1];
      scaled += (BigInt(tick) - previous.tick) * previous.scpq;
    }
    segments.push({ tick: BigInt(tick), scpq: superclocksPerQuarter(milliBpm), scaled });
  });
  return segments;
}

function toAudio(segments, ticks, sampleRate) {
  const t = BigInt(ticks);
  const rate = BigInt(sampleRate);
  let scaled;
  if (t < 0n) {
    scaled = t * segments[0].scpq;
  } else {
    const segment = [...segments].reverse().find((s) => s.tick <= t);
    scaled = segment.scaled + (t - segment.tick) * segment.scpq;
  }
  return roundHalfEven(scaled * rate, SCALED_PER_SECOND);
}

function toMusic(segments, samples, sampleRate) {
  const s = BigInt(samples);
  const rate = BigInt(sampleRate);
  const target = s * SCALED_PER_SECOND;
  if (s < 0n) {
    return roundHalfEven(target, rate * segments[0].scpq);
  }
  const segment = [...segments].reverse().find((seg, i, all) => i === all.length - 1 || seg.scaled * rate <= target);
  return segment.tick + roundHalfEven(target - segment.scaled * rate, rate * segment.scpq);
}

const MAX = 2 ** 42;
const maps = [
  { name: 'constant_120', points: [[0, 120000]] },
  { name: 'constant_140', points: [[0, 140000]] },
  { name: 'constant_tie_65_536', points: [[0, 65536]] },
  { name: 'constant_slowest', points: [[0, 1000]] },
  { name: 'constant_fastest', points: [[0, 999999]] },
  { name: 'steps_mixed', points: [[0, 120000], [3840, 60000], [7681, 97531], [20000, 123456], [1000000, 180000]] },
];
const sampleRates = [8000, 22050, 44100, 48000, 96000, 768000];
const ticks = [0, 1, 2, 3, 7, 959, 960, 1919, 1920, 3839, 3840, 3841, 7680, 7681, 7682, 19999, 20000, 123457,
  999999, 1000000, 1000001, 987654321, 2 ** 40, MAX, -1, -2, -3, -1920, -987654, -MAX];
const samples = [0, 1, 2, 11, 12, 13, 22050, 24000, 47999, 48000, 48001, 96000, 1234567, 2 ** 31, 2 ** 40, MAX,
  -1, -12, -24000, -MAX];

const cases = maps.map(({ name, points }) => {
  const segments = segmentsOf(points);
  return {
    name,
    tempoPoints: points.map(([tick, milliBpm]) => ({ ticks: String(tick), milliBpm })),
    superclocksPerQuarter: segments.map((s) => String(s.scpq)),
    conversions: sampleRates.map((sampleRate) => ({
      sampleRate,
      toAudio: ticks.map((t) => [String(t), String(toAudio(segments, t, sampleRate))]),
      toMusic: samples.map((s) => [String(s), String(toMusic(segments, s, sampleRate))]),
    })),
  };
});

const out = {
  schemaVersion: 'siann.time_fixtures.v1',
  description: 'Exact time conversions. toAudio pairs are [ticks, samples]; toMusic pairs are [samples, ticks]. 64-bit values are decimal strings. Generated by scripts/generate-time-fixtures.js with BigInt arithmetic.',
  ticksPerQuarter: Number(TICKS_PER_QUARTER),
  superclockRate: Number(SUPERCLOCK_RATE),
  cases,
};

const outFile = path.join(__dirname, '..', 'fixtures', 'time', 'conversions.json');
fs.mkdirSync(path.dirname(outFile), { recursive: true });
fs.writeFileSync(outFile, `${JSON.stringify(out, null, 2)}\n`);
console.log(`wrote ${outFile}: ${cases.length} tempo maps x ${sampleRates.length} sample rates`);
